#!/bin/sh
set -eu
export CGO_ENABLED=0
export GOWORK=off
export GOTOOLCHAIN=local

# go install module@version always asks proxy.golang.org if the module is
# deprecated. That request returns unexpected EOF often enough to fail the
# scan even when the zip is already in the mounted host module cache.
# Build the cached tree with the network disabled instead.
src="/go/pkg/mod/github.com/securego/gosec/v2@v2.22.10"
if [ ! -f "$src/go.mod" ]; then
  echo "gosec v2.22.10 is not in the mounted module cache" >&2
  exit 1
fi
cp -a "$src" /tmp/gosec-src
(
  cd /tmp/gosec-src
  GOPROXY=off GOSUMDB=off go build -mod=readonly -o /usr/local/bin/gosec ./cmd/gosec
)

scan() {
  dir="$1"
  pkgs="$2"
  echo "gosec $pkgs $dir"
  (cd "/src/$dir" && gosec -exclude-generated -fmt text $pkgs)
}

scan . ./gen/...
scan services/gateway ./...
scan services/room ./...
scan services/board ./...
scan services/chat ./...
scan services/presence ./...
scan pkg/config ./...
scan pkg/logger ./...
scan pkg/authn ./...
scan pkg/natsx ./...
scan pkg/redisx ./...
scan pkg/otelx ./...
scan pkg/grpcx ./...
